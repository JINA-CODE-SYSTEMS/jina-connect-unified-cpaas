"""Per-app ``hub.verify_token`` validation (#307).

A BSP will not deliver to a callback URL it has not verified, and it verifies one
by sending ``GET ?hub.mode=subscribe&hub.verify_token=…&hub.challenge=…`` and
requiring the challenge back. The receiver used to measure that token against a
single deployment-wide setting::

    expected_token = getattr(django_settings, "META_WEBHOOK_VERIFY_TOKEN", "")

With one platform-owned app that is fine. With #305's bring-your-own-app handover
it means every client has to be handed the *same* value — a secret shared across
tenants, and enough for any one holder to complete the handshake for another
client's endpoint and have a BSP start delivering that client's traffic
wherever they like.

So the token moves onto the app, and the test that matters is the one that could
not be written before: **app A's token fails on app B's URL.** A file asserting
only that the right token still works would pass against the old code too.

What is pinned here:

* an app's own token completes the handshake on its own URL, and on no other's;
* the deployment-wide token no longer completes a handshake on a per-app URL —
  the fallback's absence *is* the ticket, since a fallback would leave the shared
  secret sufficient everywhere;
* a mismatch is 403, is counted per app, and neither the presented token nor the
  expected one reaches a log sink;
* the legacy unsuffixed path still checks the deployment-wide setting, because it
  is the URL registered in live dashboards (#310) and has no app to ask;
* the token is generated by this deployment with a CSPRNG, is never equal between
  two apps, and cannot be chosen or overwritten through the API;
* the setup screen and the receiver agree: the token the endpoint hands a client
  is the one their URL will actually accept, which is what
  ``verify_token_scope == "app"`` is a promise about;
* Gupshup gets all of the above from the same code path, not from a second
  implementation (#305 D-4).

HOW TO RUN:
    DB_NAME=jc307 python -m pytest wa/tests/test_per_app_verify_token.py -v
"""

