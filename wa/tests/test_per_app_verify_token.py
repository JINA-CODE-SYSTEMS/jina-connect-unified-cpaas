def _tenant(prefix: str = "VerifyTokenTenant"):
    from tenants.models import Tenant

    return Tenant.objects.create(name=f"{prefix}-{uuid.uuid4().hex[:8]}", is_active=True)


def _wa_app(tenant=None, **overrides):
    from wa.models import WAApp

    fields = {
        "tenant": tenant or _tenant(),
        "app_name": f"app-{uuid.uuid4().hex[:6]}",
        "app_id": f"gs-{uuid.uuid4().hex[:8]}",
        "app_secret": "s",  # noqa: S106 — Gupshup column, unrelated to this file
        "wa_number": f"+1{uuid.uuid4().int % 10**10:010d}",
        "waba_id": f"waba-{uuid.uuid4().hex[:8]}",
        "phone_number_id": f"pn-{uuid.uuid4().hex[:8]}",
        "bsp": BSPChoices.META,
        "is_active": True,
    }
    fields.update(overrides)
    return WAApp.objects.create(**fields)


def _url(wa_app, bsp=BSPChoices.META) -> str:
    name = "wa:meta-webhook-app" if bsp == BSPChoices.META else "wa:gupshup-webhook-app"
    return reverse(name, kwargs={"webhook_identifier": wa_app.webhook_identifier})


def _handshake(client, url, token, challenge=CHALLENGE):
    query = {"hub.mode": "subscribe", "hub.challenge": challenge}
    if token is not None:
        query["hub.verify_token"] = token
    return client.get(url, query)


