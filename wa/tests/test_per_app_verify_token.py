def test_the_scope_says_deployment_only_when_that_is_what_is_checked(settings):
    """The field is a statement about the receiver, not a label.

    ``"deployment"`` has to mean the handshake really does check the shared
    setting, which after #307 is true only for an app with no token of its own.
    """
    from wa.models import WAApp

    settings.META_WEBHOOK_VERIFY_TOKEN = DEPLOYMENT_META_TOKEN

    app = _wa_app()
    assert webhook_identity.verify_token(app) == (app.webhook_verify_token, "app")

    WAApp.objects.filter(pk=app.pk).update(webhook_verify_token="")
    app.refresh_from_db()
    assert webhook_identity.verify_token(app) == (DEPLOYMENT_META_TOKEN, "deployment")

    settings.META_WEBHOOK_VERIFY_TOKEN = ""
    assert webhook_identity.verify_token(app) == ("", "none")
