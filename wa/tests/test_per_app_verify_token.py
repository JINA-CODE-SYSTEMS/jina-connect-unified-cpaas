def test_a_mismatch_is_counted_against_the_app_whose_url_was_addressed(client, settings):
    """Counted because nothing else would notice (#307).

    A client re-verifying with a stale token and someone guessing at a live one
    look the same from here; both are worth seeing. The bucket is per app so the
    count says whose endpoint is being refused.
    """
    settings.META_WEBHOOK_VERIFY_TOKEN = DEPLOYMENT_META_TOKEN
    app = _wa_app()
    bystander = _wa_app()

    # Deltas, not absolutes: the counters are shared Redis keys bucketed by UTC
    # day, and clearing the cache here would be a FLUSHDB of every other
    # process's keys too (see ``test_webhook_app_identity``).
    before = webhook_identity.verify_token_rejections(BSPChoices.META, wa_app=app)
    before_bystander = webhook_identity.verify_token_rejections(BSPChoices.META, wa_app=bystander)

    _handshake(client, _url(app), "wrong-token")
    _handshake(client, _url(app), "wrong-token-again")

    assert webhook_identity.verify_token_rejections(BSPChoices.META, wa_app=app) == before + 2
    assert webhook_identity.verify_token_rejections(BSPChoices.META, wa_app=bystander) == before_bystander
    # A successful handshake is not a rejection.
    _handshake(client, _url(app), app.webhook_verify_token)
    assert webhook_identity.verify_token_rejections(BSPChoices.META, wa_app=app) == before + 2


def test_a_legacy_path_mismatch_is_counted_too(client, settings):
    """The unsuffixed receiver has no app to attribute a refusal to, and is
    counted in its own bucket rather than not at all."""
    settings.META_WEBHOOK_VERIFY_TOKEN = DEPLOYMENT_META_TOKEN

    before = webhook_identity.verify_token_rejections(BSPChoices.META)

    assert _handshake(client, LEGACY_META_URL, "wrong-token").status_code == 403

    assert webhook_identity.verify_token_rejections(BSPChoices.META) == before + 1


def test_neither_the_presented_nor_the_expected_token_reaches_the_logs(client, settings):
    """A presented token is a guess at a secret — or another tenant's real token
    sent to the wrong endpoint. Either way a log sink is a wider audience than
    its owner agreed to, and ``got=%s`` used to put it there."""
    settings.META_WEBHOOK_VERIFY_TOKEN = DEPLOYMENT_META_TOKEN
    app = _wa_app()
    other = _wa_app()
    presented = other.webhook_verify_token

    handler, logger = _capture_wa_logs()
    try:
        response = _handshake(client, _url(app), presented)
    finally:
        logger.removeHandler(handler)

    assert response.status_code == 403

    output = handler.text
    assert presented not in output
    assert app.webhook_verify_token not in output
    assert DEPLOYMENT_META_TOKEN not in output
    # Silence is not the fix: the refusal is still reported, with the app it was
    # refused for and the scope of the token it was measured against.
    assert "mismatch" in output.lower()
    assert str(app.pk) in output
    assert "token_scope=app" in output


def test_a_successful_handshake_does_not_log_the_token_either(client, settings):
    settings.META_WEBHOOK_VERIFY_TOKEN = ""
